"""
Optional LLM summarisation grounded in retrieved abstracts (Task 4, report
section 4.5 L4).

Requires the Anthropic API: set ANTHROPIC_API_KEY in the environment.
Degrades gracefully (logs a message and skips) when the key is absent.

Usage:
  python src/rag/summarize.py \\
      --silver output/silver/pubmed_filtered \\
      --gold   output/gold \\
      --output output/gold/summaries.md

Design constraints (per project spec):
  • The prompt instructs the model to answer ONLY from the supplied abstracts.
  • Every cited PMID is checked; citations not in the retrieved set are
    removed with a warning.
  • Model name is read from config/env; no secrets are committed.
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from config import GOLD_DIR, SILVER_DIR, EMBEDDING_MODEL, FINAL_TOP_K  # noqa: E402

sys.path.insert(0, os.path.dirname(__file__))
from queries  import get_queries   # noqa: E402
from retrieve import retrieve      # noqa: E402


# ---------------------------------------------------------------------------
# Prompt template
# ---------------------------------------------------------------------------

SYSTEM_PROMPT = """\
You are a biomedical research assistant.
Answer the question using ONLY the provided abstracts.
Cite each abstract you use as (PMID: <number>).
Do NOT invent any information not present in the abstracts.
If the abstracts do not contain enough information, say so explicitly.
"""

USER_TEMPLATE = """\
Question: {query}

Abstracts:
{abstracts}

Provide a concise summary (3-5 sentences) answering the question, citing PMIDs.
"""


# ---------------------------------------------------------------------------
# Citation guard
# ---------------------------------------------------------------------------

def _check_citations(text: str, valid_pmids: set) -> str:
    """Remove any PMID citations that are NOT in the retrieved set."""
    def _replace(m):
        pmid = int(m.group(1))
        if pmid not in valid_pmids:
            print(f"[summarize] WARNING: citation PMID {pmid} not in retrieved set — removed")
            return ""
        return m.group(0)
    return re.sub(r"\(PMID:\s*(\d+)\)", _replace, text)


# ---------------------------------------------------------------------------
# LLM call
# ---------------------------------------------------------------------------

def _call_anthropic(query: str, abstracts_text: str, model: str) -> str:
    import anthropic
    client = anthropic.Anthropic()  # reads ANTHROPIC_API_KEY from environment
    message = client.messages.create(
        model=model,
        max_tokens=1024,
        system=SYSTEM_PROMPT,
        messages=[{
            "role": "user",
            "content": USER_TEMPLATE.format(
                query=query, abstracts=abstracts_text
            ),
        }],
    )
    return message.content[0].text


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def build_arg_parser():
    p = argparse.ArgumentParser(
        description="LLM summaries grounded in retrieved abstracts (optional)."
    )
    p.add_argument("--silver",  default=SILVER_DIR)
    p.add_argument("--gold",    default=GOLD_DIR)
    p.add_argument("--output",  default=os.path.join(GOLD_DIR, "summaries.md"))
    p.add_argument("--encoder", default=EMBEDDING_MODEL)
    p.add_argument("--k",       type=int, default=FINAL_TOP_K)
    p.add_argument("--model",
                   default=os.environ.get("ANTHROPIC_MODEL", "claude-3-5-haiku-20241022"),
                   help="Anthropic model name")
    return p


def summarize(silver_dir, gold_dir, output_path, encoder, k, model):
    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        print("[summarize] ANTHROPIC_API_KEY not set — skipping LLM summaries")
        return

    try:
        import anthropic  # noqa: F401
    except ImportError:
        print("[summarize] anthropic package not installed — skipping LLM summaries")
        return

    queries = get_queries()
    lines   = ["# Cancer Immunology Literature Summaries\n",
               "_Generated by Anthropic LLM, grounded in retrieved abstracts._\n"]

    for q in queries:
        print(f"[summarize] Summarising query: {q['id']}")
        hits = retrieve(
            q["query"], k=k,
            gold_dir=gold_dir, silver_dir=silver_dir,
            encoder=encoder,
        )
        valid_pmids = {h["pmid"] for h in hits}

        abstracts_text = "\n\n".join(
            f"PMID {h['pmid']}: {h.get('title','')}\n{h.get('abstract_snippet','')}"
            for h in hits
        )

        try:
            raw_summary = _call_anthropic(q["query"], abstracts_text, model)
            summary     = _check_citations(raw_summary, valid_pmids)
        except Exception as e:
            print(f"[summarize] LLM call failed for {q['id']}: {e}")
            summary = f"_(summary unavailable: {e})_"

        lines.append(f"\n## {q['id']}\n**Query:** {q['query']}\n\n{summary}\n")

    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines))
    print(f"[summarize] Wrote summaries to {output_path}")


def main():
    args = build_arg_parser().parse_args()
    summarize(args.silver, args.gold, args.output, args.encoder, args.k, args.model)


if __name__ == "__main__":
    main()
